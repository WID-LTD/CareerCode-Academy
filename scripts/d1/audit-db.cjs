// Dependency audit: which components touch the database, which tables, and
// whether they are already served natively by the D1 worker.
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '../..');
const backend = path.join(ROOT, 'backend/src');
const workers = path.join(ROOT, 'workers/src');

const read = (p) => fs.readFileSync(p, 'utf8');
const listTs = (dir) => fs.readdirSync(dir).filter((f) => f.endsWith('.ts'));

const KEYWORDS = new Set(['select', 'where', 'set', 'values', 'on', 'conflict', 'returning', 'dual', 'lateral', 'unnest', 'generate_series']);
function tablesIn(sql) {
  const out = new Set();
  for (const m of sql.matchAll(/\b(?:FROM|JOIN|INTO|UPDATE)\s+"?([a-zA-Z_][a-zA-Z0-9_]*)"?/g)) {
    const t = m[1].toLowerCase();
    if (!KEYWORDS.has(t) && !['pg_catalog', 'information_schema'].includes(t)) out.add(t);
  }
  return out;
}
function endpointsIn(src) {
  const out = [];
  for (const m of src.matchAll(/router\.(get|post|put|patch|delete)\(\s*['"`]([^'"`]+)/g)) {
    out.push(`${m[1].toUpperCase()} ${m[2]}`);
  }
  return out;
}

// backend mount points
const indexSrc = read(path.join(backend, 'index.ts'));
const mounts = {};
for (const m of indexSrc.matchAll(/app\.use\(\s*'([^']+)'\s*,\s*(\w+)\s*\)/g)) {
  const varName = m[2];
  const imp = new RegExp(`import\\s+${varName}\\s+from\\s+'([^']+)'`).exec(indexSrc);
  if (imp) mounts[path.basename(imp[1], '.ts').replace(/\.routes$/, '')] = m[1];
}

// worker native mounts
const workerIndex = read(path.join(workers, 'index.ts'));
const nativeMounts = new Set([...workerIndex.matchAll(/app\.route\('([^']+)'/g)].map((m) => m[1]));
const nativePrefixes = [...workerIndex.matchAll(/'(\/api\/v1\/[^']*)'/g)].map((m) => m[1]);
const isNative = (mount) => nativeMounts.has(mount) || nativePrefixes.some((p) => mount.startsWith(p.replace(/\/$/, '')));

// backend route -> tables (route + imported models)
const rows = [];
for (const file of listTs(path.join(backend, 'routes'))) {
  const base = file.replace('.routes.ts', '').replace('.ts', '');
  const src = read(path.join(backend, 'routes', file));
  const tables = tablesIn(src);
  const models = new Set();
  for (const m of src.matchAll(/from\s+'\.\.\/models\/([^']+)'/g)) models.add(m[1]);
  for (const model of models) {
    const mp = path.join(backend, 'models', `${model}.ts`);
    if (fs.existsSync(mp)) for (const t of tablesIn(read(mp))) tables.add(t);
  }
  const mount = mounts[base] || `(unmounted: ${base})`;
  rows.push({
    file,
    mount,
    endpoints: endpointsIn(src).length,
    tables: [...tables].sort(),
    models: [...models].sort(),
    native: isNative(mount),
  });
}

// worker-native tables
const workerTables = new Set();
for (const file of listTs(path.join(workers, 'routes'))) {
  for (const t of tablesIn(read(path.join(workers, 'routes', file)))) workerTables.add(t);
}
for (const file of ['auth-helpers.ts', 'db.ts', 'gamification.ts', 'learning-paths.ts', 'learning-path-helpers.ts']) {
  const p = path.join(workers, file);
  if (fs.existsSync(p)) for (const t of tablesIn(read(p))) workerTables.add(t);
}

const native = rows.filter((r) => r.native);
const proxied = rows.filter((r) => !r.native);
const fmt = (arr) => arr.map((r) => `| \`${r.mount}\` | ${r.endpoints} | ${r.tables.length} | ${r.tables.slice(0, 8).join(', ')}${r.tables.length > 8 ? '…' : ''} |`).join('\n');

const allTables = new Set();
for (const r of rows) for (const t of r.tables) allTables.add(t);

const out = `# Database dependency audit

Generated by \`node scripts/d1/audit-db.cjs\` on ${new Date().toISOString().slice(0, 10)}.

## Summary

| | Count |
|---|---|
| Backend route groups | ${rows.length} |
| Already native on the D1 worker | ${native.length} |
| Still proxied to Render (Neon) | ${proxied.length} |
| Endpoints still on Neon | ${proxied.reduce((s, r) => s + r.endpoints, 0)} |
| Tables referenced overall | ${allTables.size} |
| Tables referenced by native worker code | ${workerTables.size} |

The worker serves \`${native.length}\` groups from D1. Everything below under
"Still on Neon" is reachable only through the Render proxy, so Neon cannot be
retired until those are ported (or deliberately dropped).

## Native on D1

| Mount | Endpoints | Tables | Tables used |
|---|---|---|---|
${fmt(native)}

## Still on Neon (proxied to Render)

| Mount | Endpoints | Tables | Tables used |
|---|---|---|---|
${fmt(proxied.sort((a, b) => b.endpoints - a.endpoints))}

## Tables only used by not-yet-ported routes

${[...allTables].filter((t) => !workerTables.has(t)).sort().map((t) => `- \`${t}\``).join('\n')}

## Non-route DB consumers

- \`backend/src/index.ts\` — Express server, Socket.IO, cron/keepalive jobs.
- \`backend/src/config/db.ts\` — pg Pool (Neon).
- \`backend/src/models/*.ts\` — all SQL for proxied routes.
- \`backend/src/migrations/*.sql\` — Postgres schema of record (superseded by
  \`workers/sql/d1_schema.sql\` for D1).
- \`workers/src/db.ts\` — D1 client (native routes).
- \`scripts/d1/*\` — migration/backup tooling.

## Notes

- Route groups are counted from Express mount points; a group marked native is
  fully served by the worker, and its Render handler is no longer in the path.
- Table lists come from static SQL parsing (route + imported model files), so
  dynamically built SQL may under-report.
`;

fs.writeFileSync(path.join(ROOT, 'docs/DB-AUDIT.md'), out);
console.log(`AUDIT: ${native.length} native / ${proxied.length} proxied / ${proxied.reduce((s, r) => s + r.endpoints, 0)} endpoints on Neon`);
console.log('proxied:', proxied.sort((a, b) => b.endpoints - a.endpoints).map((r) => `${r.mount}(${r.endpoints})`).join(' '));
