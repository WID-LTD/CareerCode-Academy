// Generate workers/sql/d1_schema.sql (SQLite DDL) from neon-schema.json.
// Usage: node scripts/d1/gen-schema.cjs > workers/sql/d1_schema.sql
const fs = require('fs');
const path = require('path');
const { tables, cons, idx } = require('./neon-schema.json');

const UUID_EXPR = `(lower(hex(randomblob(4))) || '-' || lower(hex(randomblob(2))) || '-4' || substr(lower(hex(randomblob(2))),2) || '-' || substr('89ab',abs(random()) % 4 + 1, 1) || substr(lower(hex(randomblob(2))),2) || '-' || lower(hex(randomblob(6))))`;
const NOW_EXPR = `(strftime('%Y-%m-%dT%H:%M:%fZ','now'))`;

const mapType = (c) => {
  switch (c.udt_name) {
    case 'bool': return 'INTEGER';
    case 'int2': case 'int4': case 'int8': return 'INTEGER';
    case 'numeric': case 'float4': case 'float8': return 'REAL';
    default: return 'TEXT'; // uuid, text, varchar, timestamps, jsonb, arrays
  }
};

function mapDefault(d) {
  if (!d) return null;
  const x = d.trim();
  if (/^gen_random_uuid\(\)$/.test(x)) return UUID_EXPR;
  if (/^now\(\)$/.test(x)) return NOW_EXPR;
  if (/^CURRENT_DATE$/i.test(x)) return `(date('now'))`;
  if (/^nextval\(/i.test(x)) return null;
  if (/^ARRAY\[/i.test(x)) {
    const inner = x.slice(x.indexOf('[') + 1, x.lastIndexOf(']')).replace(/::[a-z ]+/gi, '').trim();
    return `'[${inner}]'`;
  }
  if (/\[\]$/.test(x) || /\((uuid|text|jsonb|integer)\[\]$/.test(x)) {
    if (/^'\{\}'/.test(x)) return "'[]'";
  }
  let v = x.replace(/::(character varying|character|text|jsonb|json|uuid|timestamp with time zone|timestamp without time zone|numeric|integer|bigint|boolean|text\[\]|jsonb\[\]|interval)/gi, '');
  if (/^'(.*)'$/s.test(v)) return `'${RegExp.$1.replace(/'/g, "''")}'`;
  if (/^(true|false)$/i.test(v)) return v.toLowerCase() === 'true' ? '1' : '0';
  if (/^-?\d+(\.\d+)?$/.test(v)) return v;
  return null;
}

const byTable = new Map();
for (const c of cons) {
  if (!byTable.has(c.table_name)) byTable.set(c.table_name, []);
  byTable.get(c.table_name).push(c);
}

const out = [
  '-- CareerCode Academy — Cloudflare D1 (SQLite) schema',
  '-- Generated by scripts/d1/gen-schema.cjs from the live Neon schema.',
  'PRAGMA foreign_keys = ON;',
  '',
];

for (const t of tables.map((x) => x.table).sort()) {
  const cs = byTable.get(t) || [];
  const cols = tables.find((x) => x.table === t).cols;
  const lines = cols.map((c) => {
    let line = `  "${c.column_name}" ${mapType(c)}`;
    if (c.is_nullable === 'NO') line += ' NOT NULL';
    const def = mapDefault(c.column_default);
    if (def) line += ` DEFAULT ${def}`;
    return line;
  });
  const pk = cs.find((c) => c.contype === 'p');
  if (pk) {
    const m = /PRIMARY KEY \(([^)]+)\)/.exec(pk.def);
    if (m) lines.push(`  PRIMARY KEY (${m[1].split(',').map((s) => `"${s.trim()}"`).join(', ')})`);
  }
  for (const u of cs.filter((c) => c.contype === 'u')) {
    const m = /UNIQUE \(([^)]+)\)/.exec(u.def);
    if (m) lines.push(`  UNIQUE (${m[1]})`);
  }
  for (const f of cs.filter((c) => c.contype === 'f')) {
    const m = /FOREIGN KEY \(([^)]+)\) REFERENCES ([^(]+)\(([^)]+)\)(.*)$/.exec(f.def);
    if (!m) continue;
    const del = /ON DELETE (CASCADE|SET NULL|RESTRICT|NO ACTION)/i.exec(f.def);
    lines.push(`  FOREIGN KEY (${m[1]}) REFERENCES "${m[2].trim()}"(${m[3]})${del ? ' ON DELETE ' + del[1].toUpperCase() : ''}`);
  }
  for (const chk of cs.filter((c) => c.contype === 'c')) {
    const m = /^CHECK \((.*)\)$/s.exec(chk.def);
    if (!m) continue;
    let body = m[1].replace(/::(character varying|text|uuid|integer|numeric|bigint|boolean)/gi, '');
    body = body.replace(/\(?\s*\(?([\w.]+)\)?\s*=\s*ANY\s*\(\s*\(?\s*ARRAY\s*\[([^\]]*)\]\s*\)?\s*\)\s*\)?/gi, '$1 IN ($2)');
    if (/\bANY\b|\bALL\b|\[\]/i.test(body)) continue;
    lines.push(`  CHECK (${body})`);
  }
  out.push(`CREATE TABLE IF NOT EXISTS "${t}" (\n${lines.join(',\n')}\n);`);
}

out.push('', '-- Secondary indexes');
for (const i of idx) {
  if (/ PRIMARY KEY /.test(i.indexdef)) continue;
  const m = /^CREATE (UNIQUE )?INDEX (\S+) ON (?:public\.)?(\S+) USING (\w+) \((.*)\)$/s.exec(i.indexdef);
  if (!m || m[4] !== 'btree' || /[()]/.test(m[5])) {
    out.push(`-- SKIP: ${i.indexdef}`);
    continue;
  }
  const cols = m[5].replace(/\s+(ASC|DESC)\b/gi, '').replace(/\s+NULLS (FIRST|LAST)/gi, '');
  out.push(`CREATE ${m[1] ? 'UNIQUE ' : ''}INDEX IF NOT EXISTS "${m[2]}" ON "${m[3]}" (${cols});`);
}

process.stdout.write(out.join('\n') + '\n');
