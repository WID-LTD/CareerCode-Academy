// Generate workers/src/schema-types.ts from the introspected Neon schema.
const fs = require('fs');
const path = require('path');
const { tables } = require('./neon-schema.json');

const bool = new Set();
const json = new Set();
const jsonOwner = {}; // column -> tables where it is jsonb
for (const t of tables) {
  for (const c of t.cols) {
    if (c.udt_name === 'bool') bool.add(c.column_name);
    if (c.udt_name === 'jsonb') {
      json.add(c.column_name);
      (jsonOwner[c.column_name] ||= []).push(t.table);
    }
  }
}
// Columns with the same name but different types need a table hint.
const arrays = new Set();
for (const t of tables) for (const c of t.cols) if (c.udt_name.startsWith('_')) arrays.add(c.column_name);

const numeric = {}; // column -> scale (2) or null for unconstrained numeric
for (const t of tables) {
  for (const c of t.cols) {
    if (c.udt_name !== 'numeric') continue;
    const scale = c.numeric_scale === null ? null : Number(c.numeric_scale);
    if (!(c.column_name in numeric)) numeric[c.column_name] = scale;
    else if (numeric[c.column_name] !== scale) numeric[c.column_name] = null;
  }
}

const ambiguous = {};
for (const [col, owners] of Object.entries(jsonOwner)) {
  const others = tables.some((t) => t.cols.some((c) => c.column_name === col && c.udt_name !== 'jsonb'));
  if (others) ambiguous[col] = owners;
}
for (const col of Object.keys(ambiguous)) json.delete(col);

const q = (s) => `'${s.replace(/'/g, "\\'")}'`;
const out = `// AUTO-GENERATED by scripts/d1/gen-types.cjs — do not edit by hand.
// Column types D1/SQLite flattens but the API contract expects to keep:
// booleans as true/false and jsonb as parsed JSON (Postgres did this for us).

export const BOOL_COLUMNS: ReadonlySet<string> = new Set([
${[...bool].sort().map((c) => `  ${q(c)},`).join('\n')}
]);

export const JSON_COLUMNS: ReadonlySet<string> = new Set([
${[...json].sort().map((c) => `  ${q(c)},`).join('\n')}
]);

// jsonb columns whose name is also used for a plain text column elsewhere.
// Only parse when the query actually touches the owning table.
// Postgres array columns (text[], uuid[], ...) come back as JSON text in D1.
export const ARRAY_COLUMNS: ReadonlySet<string> = new Set([
${[...arrays].sort().map((c) => `  ${q(c)},`).join('\n')}
]);

// Postgres returns NUMERIC columns as fixed-scale strings ("8500.00"); SQLite
// returns REAL numbers. Restore the original representation.
export const NUMERIC_SCALE: Readonly<Record<string, number | null>> = {
${Object.entries(numeric).sort().map(([c, sc]) => `  ${q(c)}: ${sc},`).join('\n')}
};

export const AMBIGUOUS_JSON_COLUMNS: Readonly<Record<string, readonly string[]>> = {
${Object.entries(ambiguous).map(([col, owners]) => `  ${q(col)}: [${owners.map(q).join(', ')}],`).join('\n')}
};
`;
fs.writeFileSync(path.join(__dirname, '../../workers/src/schema-types.ts'), out);
console.log('WROTE schema-types.ts', 'bool', bool.size, 'json', json.size, 'ambiguous', Object.keys(ambiguous));
