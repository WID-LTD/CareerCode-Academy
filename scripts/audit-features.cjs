// Deep feature audit: every API path the frontend calls, where it resolves,
// and which dashboard pages still depend on the Render proxy.
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const FE = path.join(ROOT, 'frontend/src');
const walk = (dir) => fs.readdirSync(dir, { withFileTypes: true }).flatMap((e) =>
  e.isDirectory() ? walk(path.join(dir, e.name)) : [path.join(dir, e.name)]);
const files = walk(FE).filter((f) => /\.(ts|tsx)$/.test(f) && !f.includes('__tests__'));

const calls = new Map(); // path -> Set(files)
for (const f of files) {
  const src = fs.readFileSync(f, 'utf8');
  const re = /\bapi\.(?:get|post|put|patch|delete)\(\s*(?:`([^`]+)`|'([^']+)'|"([^"]+)")/g;
  for (const m of src.matchAll(re)) {
    let p = (m[1] || m[2] || m[3] || '').trim();
    if (!p.startsWith('/')) continue;
    p = p.split('?')[0];
    // collapse template interpolations to a placeholder
    p = p.replace(/\$\{[^}]+\}/g, ':x');
    if (!calls.has(p)) calls.set(p, new Set());
    calls.get(p).add(path.relative(FE, f));
  }
  // axios instance with absolute /api/v1 paths
  for (const m of src.matchAll(/['"`](\/api\/v1\/[^'"`?]+)/g)) {
    const p = m[1].replace(/\$\{[^}]+\}/g, ':x');
    if (!calls.has(p)) calls.set(p, new Set());
    calls.get(p).add(path.relative(FE, f));
  }
}

// backend mounts
const backendIndex = fs.readFileSync(path.join(ROOT, 'backend/src/index.ts'), 'utf8');
const backendMounts = [...backendIndex.matchAll(/app\.use\(\s*'([^']+)'/g)].map((m) => m[1]);
// worker native mounts
const workerIndex = fs.readFileSync(path.join(ROOT, 'workers/src/index.ts'), 'utf8');
const nativeMounts = [...workerIndex.matchAll(/app\.route\('([^']+)'/g)].map((m) => m[1]);

const matchMount = (p, mounts) => mounts.find((m) => p === m || p.startsWith(m + '/')) || null;
const norm = (p) => (p.startsWith('/api/v1') ? p : `/api/v1${p}`);

const rows = [...calls.entries()].map(([raw, usedBy]) => {
  const p = norm(raw);
  const backend = matchMount(p, backendMounts);
  const native = matchMount(p, nativeMounts);
  return { path: p, backend, native, usedBy: [...usedBy] };
}).sort((a, b) => a.path.localeCompare(b.path));

const dead = rows.filter((r) => !r.backend && !r.native);
const proxied = rows.filter((r) => r.backend && !r.native);
const native = rows.filter((r) => r.native);

// dashboard pages + their API dependencies
const dashboards = walk(FE).filter((f) => /pages\/(student|instructor|admin)\//.test(f));
const pageRows = dashboards.map((f) => {
  const src = fs.readFileSync(f, 'utf8');
  const paths = new Set();
  for (const m of src.matchAll(/\bapi\.(?:get|post|put|patch|delete)\(\s*(?:`([^`]+)`|'([^']+)'|"([^"]+)")/g)) {
    let p = (m[1] || m[2] || m[3] || '').trim();
    if (!p.startsWith('/')) continue;
    p = norm(p.split('?')[0].replace(/\$\{[^}]+\}/g, ':x'));
    paths.add(p);
  }
  const arr = [...paths];
  const proxiedPaths = arr.filter((p) => matchMount(p, backendMounts) && !matchMount(p, nativeMounts));
  return { page: path.relative(FE, f), total: arr.length, proxied: proxiedPaths };
});

const out = `# Feature audit

Generated by \`node scripts/audit-features.cjs\` on ${new Date().toISOString().slice(0, 10)}.

## API usage

| | Count |
|---|---|
| Distinct API paths called by the frontend | ${rows.length} |
| Served natively by the D1 worker | ${native.length} |
| Still proxied to Render (Neon) | ${proxied.length} |
| Called by the frontend but matching no mount | ${dead.length} |

## Still proxied (frontend-visible)

| Path | Used by |
|---|---|
${proxied.map((r) => `| \`${r.path}\` | ${r.usedBy.slice(0, 3).map((f) => `\`${f}\``).join(', ')}${r.usedBy.length > 3 ? ` +${r.usedBy.length - 3}` : ''} |`).join('\n')}

## Dead calls (no matching backend mount)

${dead.length ? dead.map((r) => `- \`${r.path}\` — ${r.usedBy.join(', ')}`).join('\n') : 'None found.'}

## Dashboard pages

| Page | API calls | Still proxied |
|---|---|---|
${pageRows.sort((a, b) => b.proxied.length - a.proxied.length).map((r) => `| \`${r.page}\` | ${r.total} | ${r.proxied.length ? r.proxied.slice(0, 4).map((p) => `\`${p}\``).join(', ') + (r.proxied.length > 4 ? ` +${r.proxied.length - 4}` : '') : '—'} |`).join('\n')}
`;

fs.writeFileSync(path.join(ROOT, 'docs/FEATURE-AUDIT.md'), out);
console.log(`API paths ${rows.length} | native ${native.length} | proxied ${proxied.length} | dead ${dead.length}`);
console.log('DEAD:', dead.map((d) => d.path).join(' ') || 'none');
